<#
Reset the "Customer 360 - Working Copy" semantic model to the flawed as-is state.
Run this after a rehearsal (the agent's changes through the XMLA endpoint can't be undone or downloaded as a .pbix).

Prerequisites: Azure CLI signed in to the tenant that owns the workspace (az login), the as-is TMDL generated by
fabric/as-is-model/gen_asis_tmdl.py, and permission to create items in the workspace.

Usage:
  .\reset_working_copy.ps1 -WorkspaceName "Model Detective Agency" -SqlEndpoint "<lakehouse SQL endpoint>" -SchemaJson "<schema.json>"
#>
param(
  [Parameter(Mandatory)] [string] $WorkspaceName,
  [Parameter(Mandatory)] [string] $SqlEndpoint,
  [Parameter(Mandatory)] [string] $SchemaJson,
  [string] $ModelName = "Customer 360 - Working Copy"
)
$ErrorActionPreference = "Stop"
$tok = az account get-access-token --resource https://api.fabric.microsoft.com --query accessToken -o tsv
$h = @{ Authorization = "Bearer $tok"; "Content-Type" = "application/json" }
$api = "https://api.fabric.microsoft.com/v1"

$ws = (Invoke-RestMethod "$api/workspaces" -Headers $h).value | Where-Object { $_.displayName -like "*$WorkspaceName" } | Select-Object -First 1
if (-not $ws) { throw "Workspace '$WorkspaceName' not found" }

# 1. delete the old working copy (if any)
$old = (Invoke-RestMethod "$api/workspaces/$($ws.id)/semanticModels" -Headers $h).value | Where-Object { $_.displayName -eq $ModelName }
if ($old) { $d = Invoke-WebRequest -Method Delete "$api/workspaces/$($ws.id)/semanticModels/$($old.id)" -Headers $h -SkipHttpErrorCheck -TimeoutSec 60; if ($d.StatusCode -ne 200) { throw "Delete failed: $($d.StatusCode) $($d.Content)" }; Start-Sleep 5 }

# 2. regenerate the as-is TMDL and deploy it under the same name
$tmp = Join-Path $env:TEMP "asis_reset"; Remove-Item $tmp -Recurse -Force -ErrorAction SilentlyContinue
python "$PSScriptRoot\gen_asis_tmdl.py" $SchemaJson $SqlEndpoint $tmp | Out-Null
Push-Location $tmp
$parts = Get-ChildItem -Recurse -File | ForEach-Object {
  @{ path = (Resolve-Path $_.FullName -Relative).Substring(2).Replace("\", "/"); payload = [Convert]::ToBase64String([IO.File]::ReadAllBytes($_.FullName)); payloadType = "InlineBase64" } }
Pop-Location
$body = @{ displayName = $ModelName; type = "SemanticModel"; definition = @{ parts = @($parts) } } | ConvertTo-Json -Depth 8
$r = Invoke-WebRequest -Method Post "$api/workspaces/$($ws.id)/items" -Headers $h -Body $body -SkipHttpErrorCheck
$loc = $r.Headers["Location"] | Select-Object -First 1
for ($i = 0; $i -lt 24; $i++) { Start-Sleep 5; $op = Invoke-RestMethod $loc -Headers @{ Authorization = "Bearer $tok" }; if ($op.status -notin "Running", "NotStarted") { break } }
if ($op.status -ne "Succeeded") { throw "Deploy failed: $($op.error.message)" }
Write-Host "Deployed '$ModelName'. Next: Settings > Gateway and cloud connections > map to your connection > Apply, then refresh."